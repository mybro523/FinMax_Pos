// ── Часы программы ──
//
// Время чека нельзя брать просто с часов компьютера: на кассах они спешат, отстают,
// а иногда стоят на прошлом годе. На сайте это решено сверкой с сервером по каждому
// ответу. Программа работает и без сервера, поэтому ей нужно больше.
//
// Правила:
//   1. Пока есть связь — время серверное: поправка берётся из каждого ответа сервера.
//   2. Поправка запоминается на диске. Часы компьютера, которые врут на час, врут
//      на тот же час и завтра — после перезапуска без интернета время останется верным.
//   3. Перевод часов компьютера на время программы не влияет: внутри одного запуска
//      оно отсчитывается по секундомеру системы, который переводом часов не сдвинуть.
//      А между запусками помнится последний увиденный момент — раньше него программа
//      время не покажет.
//   4. Чего программа не знает, она не выдумывает. Если после запуска ни часы
//      компьютера с поправкой, ни сами часы не дают правдоподобного времени (они
//      показывают раньше уже увиденного: их перевели назад, села батарейка на плате),
//      сколько программа была выключена, узнать не у кого. Это «неуверенный» режим:
//        • у программы есть «верное» время — последний увиденный момент плюс то, что
//          она насчитала сама; раньше него время не бывает;
//        • если часы компьютера показывают больше (их поправили), время берётся с них —
//          сразу, без перезапуска. И так же возвращается, если их поправили ещё раз:
//          опечатка в дате не должна оставаться в программе до появления связи;
//        • пока часы компьютера показывают меньше «верного» времени или немыслимо
//          больше, человеку говорится прямо: часам верить нельзя (doubtful).
//      Режим заканчивается первым же ответом сервера.
//      Цена этого правила: в неуверенном режиме время может пойти назад — если дату на
//      компьютере перевели назад. Чек после такой поправки окажется «раньше» чека до
//      неё. Это осознанно: чеки с опечаткой в дате неверны в любом случае, а следующие
//      должны быть верными уже сейчас, а не после появления связи. Деньги и остатки от
//      порядка дат не зависят: смена считается по своим чекам, очередь — по номерам.
//   5. У срока работы без связи — своё время (lic). Оно не идёт за часами компьютера,
//      которым нельзя верить: иначе опечатка в дате («не тот месяц») заперла бы кассу
//      до появления интернета. А за запуск, после которого неизвестно, сколько
//      программа была выключена, срок уменьшается так, как если бы она была выключена
//      «как обычно». Что значит «обычно», программа знает сама: пока часам можно
//      верить, она запоминает, сколько часов простоя приходится у этого компьютера на
//      час работы. Магазин, где компьютер работает десять часов и выключен четырнадцать,
//      получит за ночь свои четырнадцать; круглосуточная, где свет мигает трижды в
//      день, — почти ничего. Считать «полсуток за каждое включение» нельзя: первой
//      неделя без связи растягивалась бы, у второй сгорала бы за три дня. А не считать
//      простой вовсе — значит считать одни рабочие часы: неделя превратилась бы в две
//      с половиной.
//
// Откуда брать часы и секундомер и куда записывать, передаётся снаружи: модуль
// проверяется обычными тестами, без ожидания настоящего времени.

// Меньше этого — не «перевели назад», а обычная неточность
const BACK_SLACK_MS = 5 * 60 * 1000
// Дальше этого от последнего увиденного момента времени не верим: касса может
// простоять выключенной сезон, но не годы. Так отсекается и поправка «плюс
// одиннадцать лет», оставшаяся от загрузки с неверным годом, и опечатка в годе
const FAR_MS = 400 * 86400000
// Запомненной поправке больше этого верим, только если без неё время выходит раньше
// уже увиденного. Когда правдоподобны оба времени — и с поправкой, и без, — берётся
// меньшее: часы могли починить, пока программа была закрыта, и тогда поправка устарела.
// Отстать на её величину до появления связи не страшно; убежать вперёд — значит
// потерять срок работы без связи
const TRUST_MS = 12 * 3600 * 1000
// Время сервера приходит с точностью до секунды. Расхождение в пределах этой
// неточности часы не двигает: иначе каждый ответ дёргал бы время на доли секунды
// туда-сюда, и чек мог бы оказаться «раньше» предыдущего
const JITTER_MS = 2000
// В неуверенном режиме время идёт по часам компьютера, а их подводят на секунды.
// Шаг назад меньше этого время не двигает; больше — значит, дату поправил человек
const HOLD_MS = 2 * 60 * 1000
// ── Ритм компьютера: сколько простоя приходится на час работы ──
// Пока своих наблюдений мало (меньше стольких часов работы), считаем «час на час»
const RHYTHM_MIN_MS = 6 * 3600 * 1000
export const RHYTHM_DEFAULT = 1
// Больше двух часов простоя на час работы не считаем: это рабочий день короче восьми
// часов, и ошибиться здесь лучше в пользу магазина
const RHYTHM_MAX = 2
// Один простой учится не больше чем на столько: ночь — да, а неделя отпуска о том, как
// компьютер работает обычно, ничего не говорит
const GAP_LEARN_MAX_MS = 16 * 3600 * 1000
// Наблюдения старше примерно полутора месяцев постепенно забываются
const RHYTHM_MEMORY_MS = 21 * 86400000
// Работа и простой после неё вместе — не больше суток: проработала десять часов —
// простой считается не длиннее четырнадцати; проработала сутки подряд и дольше —
// компьютер на ночь не выключают, и простоя не было
const CYCLE_MS = 24 * 3600 * 1000
// Строки часов нет, а отметка о проверке подписки есть (строку стёрли): сколько
// программа проработала до простоя, неизвестно — считаем, что обычный рабочий день
const OWED_UNKNOWN_MS = 12 * 3600 * 1000

const num = (v) => (Number.isFinite(v) ? v : 0)

export function createClock({ wall = () => Date.now(), mono = () => performance.now(), load = () => null, save = () => {} } = {}) {
  let offset = 0 // на сколько время программы впереди часов компьютера
  // «Верное» время: момент, от которого идёт отсчёт, и показание секундомера в этот момент
  let anchorT = 0
  let anchorM = 0
  // Неуверенный режим (правило 4)
  let unsure = false
  // Время для срока работы без связи (правило 5) — со своим отсчётом
  let licT = 0
  let licM = 0
  // Ритм компьютера: сколько он работал и сколько простаивал, пока часам можно было верить
  let on = 0
  let off = 0
  // Сколько программа проработала с последнего простоя, длина которого известна или учтена
  let owed = 0
  // Неизвестные простои с тех пор, как время в последний раз было верным: сколько их
  // и сколько программа проработала перед ними. Ответит сервер — узнаем, сколько они
  // длились на самом деле, и запомним
  let lostRun = 0
  let lostGaps = 0
  const bornM = mono()
  // Последнее показанное время — чтобы в неуверенном режиме оно не дёргалось назад
  let shown = 0

  const anchor = (t) => {
    anchorT = t
    anchorM = mono()
  }
  const sure = () => anchorT + (mono() - anchorM)
  const anchorLic = (t) => {
    licT = t
    licM = mono()
  }

  // ── Запуск ──
  const saved = load() || {}
  offset = num(saved.offset)
  // Последний увиденный момент «верного» времени
  const seen = num(saved.seen)
  // До какого момента дожил срок работы без связи: из строки часов и из зашифрованной
  // записи о проверке подписки (её передаёт основная часть — стереть её нельзя)
  const licSeen = Math.max(num(saved.lic), num(saved.licSeen))
  on = Math.max(0, num(saved.on))
  off = Math.max(0, num(saved.off))
  owed = Number.isFinite(saved.owed) ? Math.max(0, saved.owed) : seen || licSeen ? OWED_UNKNOWN_MS : 0
  lostRun = Math.max(0, num(saved.lostRun))
  lostGaps = Math.max(0, Math.trunc(num(saved.lostGaps)))

  // Сколько часов простоя приходится на час работы — по своим наблюдениям
  const rhythm = () => (on >= RHYTHM_MIN_MS ? Math.min(RHYTHM_MAX, off / on) : RHYTHM_DEFAULT)
  // Запомнить: проработала столько-то, потом простояла столько-то (gaps простоев).
  // Простой учится в меру работы перед ним: закрыли и открыли программу, а потом ушли в
  // отпуск — это не «за минуту работы две недели простоя»
  const learn = (run, idle, gaps = 1) => {
    const worked = Math.max(0, run)
    on += worked
    off += Math.min(Math.max(0, idle), GAP_LEARN_MAX_MS * gaps, RHYTHM_MAX * worked)
    if (on + off > RHYTHM_MEMORY_MS) {
      on /= 2
      off /= 2
    }
  }

  const w0 = wall()
  // «Который час» после запуска — обычно это часы компьютера с запомненной поправкой
  const usual = w0 + offset
  // Правдоподобно: не раньше уже увиденного и не немыслимо позже
  const near = (t) => t >= seen - BACK_SLACK_MS && t - seen <= FAR_MS
  let start
  // Сколько программа была выключена, узнать не удалось
  let gap = false
  if (!seen) {
    // Первый запуск: сверяться не с чем
    start = usual
  } else if (saved.unsure === true) {
    // Прошлый запуск закончился в неуверенном режиме, сервер так и не ответил.
    // Часы компьютера тогда показывали прошлое, а теперь нет — их перевели, пока
    // программа была закрыта. Их ход за это время ничего не говорит о том, сколько
    // прошло: в нём сидит и сама поправка. Иначе (сбитые часы просто идут дальше или
    // исправные идут как шли) их ходу верим: программу закрыли и открыли снова
    unsure = true
    const moved = saved.behind === true && w0 >= seen - BACK_SLACK_MS
    if (near(usual) && !moved) start = Math.max(usual, seen)
    else {
      start = seen
      gap = true
    }
  } else if (near(usual) && near(w0) && Math.abs(offset) > TRUST_MS) {
    // Правдоподобны оба, а разница большая — берём меньшее (см. TRUST_MS)
    if (w0 < usual) {
      start = Math.max(w0, seen)
      offset = 0
    } else start = Math.max(usual, seen)
  } else if (near(usual)) {
    start = Math.max(usual, seen)
  } else if (near(w0)) {
    // С поправкой время неправдоподобно, а сами часы компьютера правдоподобны: их
    // исправили, пока программа была закрыта. (Компьютер когда-то загрузился с 2015
    // годом, поправка вышла «плюс одиннадцать лет», часы починили — с ней был бы 2038-й)
    start = Math.max(w0, seen)
    offset = 0
  } else {
    unsure = true
    start = seen
    gap = true
  }
  anchor(start)

  // Срок работы без связи. В обычном режиме его время — время программы (но не раньше
  // зашифрованной отметки). В неуверенном оно идёт само: что насчитала программа, плюс
  // неизвестный простой — по ритму компьютера (правило 5)
  if (unsure) {
    let lic = Math.max(licSeen, seen) + (start - seen)
    if (gap) {
      lic += Math.min(rhythm() * owed, Math.max(0, CYCLE_MS - owed))
      lostRun += owed
      lostGaps += 1
    }
    anchorLic(lic)
  } else {
    // Сколько программа была выключена, известно — ритм запоминается
    if (seen) learn(owed, start - seen)
    lostRun = 0
    lostGaps = 0
    anchorLic(Math.max(start, licSeen))
  }
  // Простой учтён (измерен или оценён) — счёт работы «до следующего простоя» начинается заново
  owed = 0

  const now = () => {
    const s = sure()
    if (!unsure) return Math.round(s)
    // Не раньше «верного» времени; часы компьютера показывают больше (но не немыслимо
    // больше) — время по ним
    const w = wall()
    let v = w > s && w - s <= FAR_MS ? w : s
    if (v < shown && shown - v < HOLD_MS) v = shown
    shown = v
    return Math.round(v)
  }

  // Время для срока работы без связи
  const lic = () => {
    const l = licT + (mono() - licM)
    return Math.round(unsure ? l : Math.max(l, sure()))
  }

  const persist = () => {
    // Поправка запоминается такой, какая она сейчас: «время программы минус часы
    // компьютера». Часы компьютера могли перевести, пока программа работала (Windows
    // сверила время, владелец поправил дату) — время программы от этого не изменилось,
    // а поправка стала другой. Запомни мы прежнюю, следующий запуск начался бы не с
    // того времени: на час назад, на сутки вперёд, а то и в другом году.
    // Запоминается «верное» время, а не показанное: в неуверенном режиме показанное
    // взято с часов компьютера, и если в них опечатка, она не должна стать отметкой,
    // раньше которой время уже не вернётся
    const s = sure()
    const w = wall()
    offset = s - w
    try {
      save({
        offset,
        seen: Math.round(s),
        unsure,
        behind: unsure && w < s - BACK_SLACK_MS,
        lic: lic(),
        on: Math.round(on),
        off: Math.round(off),
        owed: Math.round(owed + (mono() - bornM)),
        lostRun: Math.round(lostRun),
        lostGaps,
      })
    } catch {
      /* диск недоступен — время идёт дальше, запомним в следующий раз */
    }
  }

  return {
    now,
    date: () => new Date(now()),
    iso: () => new Date(now()).toISOString(),

    // Сервер ответил — вот его время (заголовок Date). Сервер прав всегда: если мы
    // успели уйти вперёд из-за сбитых часов, возвращаемся к его времени.
    // ageMs — сколько прошло с момента, когда пришли заголовки ответа: большой список
    // по слабой связи дочитывается десятки секунд, и время в заголовке успевает устареть.
    serverTime(dateHeader, ageMs = 0) {
      const t = Date.parse(dateHeader || '')
      if (!Number.isFinite(t)) return false
      // Заголовок называет секунду, когда сервер начал отвечать. Её середина плюс время,
      // за которое ответ дочитали, — лучшее, что можно сказать о «сейчас»
      const est = t + 500 + Math.max(0, Number(ageMs) || 0)
      if (!unsure && Math.abs(est - sure()) < JITTER_MS) {
        // Время не трогаем, а поправку к часам компьютера обновляем (см. persist).
        // Срок работы без связи считается от времени, которое подтвердил сервер
        offset = sure() - wall()
        anchorLic(sure())
        return true
      }
      // Сервер назвал время — неуверенному режиму конец. Заодно стало известно,
      // сколько на самом деле длились простои, которые приходилось оценивать: всё,
      // чего не хватает «верному» времени до настоящего. Это запоминается — так ритм
      // узнаёт и компьютер, на котором часы сбиваются при каждом включении
      if (unsure && lostGaps > 0) learn(lostRun, est - sure(), lostGaps)
      lostRun = 0
      lostGaps = 0
      unsure = false
      shown = 0
      anchor(est)
      anchorLic(est)
      persist()
      return true
    },

    // Запомнить «сейчас» на диске. Вызывается раз в полминуты и при выходе: после
    // перезапуска время продолжится не раньше этой отметки.
    persist,
    offset: () => sure() - wall(),
    // Часам компьютера сейчас верить нельзя: они показывают время раньше того, что
    // программа насчитала сама, или немыслимо далёкое, а сервер ещё не ответил
    doubtful: () => {
      if (!unsure) return false
      const s = sure()
      const w = wall()
      return w < s - BACK_SLACK_MS || w - s > FAR_MS
    },
    // Время не сверено с сервером и идёт по часам компьютера (неуверенный режим)
    unverified: () => unsure,
    // Время для срока работы без связи и «верное» время — для зашифрованной отметки
    lic,
    floor: () => Math.round(sure()),
    // Сколько часов простоя приходится на час работы этого компьютера (для проверок)
    rhythm,
  }
}
