// Общий текст, когда код незнакомый: кассир должен понять, что чек НЕ зарегистрирован
export const FISCAL_FALLBACK = 'Фискальный принтер не зарегистрировал чек. Повторите попытку.'

export const fiscalMessage = (code) => BY_CODE[code] || FISCAL_FALLBACK

// Результат запроса к устройству (client.mjs) → текст для человека. Успех — пусто.
export function fiscalHuman(r) {
  if (!r || r.ok) return ''
  return r.net ? NET[r.net] || NET.badReply : fiscalMessage(r.code)
}

// Полный список текстов — для сверки с переводом на таджикский (i18n)
