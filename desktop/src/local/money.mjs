// ── Деньги в локальной базе ──
//
// Чек, пробитый без интернета, уже напечатан и деньги по нему взяты. Когда он дойдёт
// до сервера, суммы обязаны сойтись до дирама — не «примерно», а точно.
//
// Сервер считает деньги библиотекой точных десятичных чисел (decimal.js внутри
// Prisma): двадцать значащих цифр, округление «половина — от нуля». Здесь стоит
// ТА ЖЕ библиотека той же версии с теми же настройками. Это не вопрос вкуса:
// «более точный» счёт дал бы другой ответ. Три штуки из пачки в двенадцать штук
// по 2,50 — это ровно 0,625, но сервер делит 2,5 на 12 с двадцатью цифрами и
// получает 0,62499999999999999999, то есть 62 дирама, а не 63. Касса должна
// ошибаться и попадать ровно там же, где сервер, — иначе чек и база разойдутся.
//
// Хранятся суммы в дирамах, целыми числами: в базе сервера у них ровно два знака
// после запятой, а целое число не теряет точности ни при сложении, ни при записи.
import Decimal from 'decimal.js'

// Своя копия настроек: даже если кто-то в программе изменит общие, счёт денег
// останется таким же, как на сервере
const Dec = Decimal.clone({ precision: 20, rounding: Decimal.ROUND_HALF_UP })

// Точное число из того, что прислало окно или что лежит в базе. Пусто — ноль.
// Мусор («abc», бесконечность) тоже ноль: считать с ним нельзя, а упасть посреди
// продажи из-за одного поля хуже, чем отказать по понятной причине выше по коду.
export function D(v = 0) {
  if (v instanceof Dec) return v
  try {
    const d = new Dec(v ?? 0)
    return d.isFinite() ? d : new Dec(0)
  } catch {
    return new Dec(0)
  }
}

export const ZERO = D(0)
export const dmin = (a, b) => Dec.min(D(a), D(b))
export const dmax = (a, b) => Dec.max(D(a), D(b))

// Точная сумма → дирамы. Так округляет база сервера, когда кладёт сумму в столбец
// с двумя знаками: до ближайшего, половина — от нуля.
export const toCents = (v) => Number(D(v).times(100).toDecimalPlaces(0, Dec.ROUND_HALF_UP).toFixed(0))

// Дирамы → точное число сомони (для дальнейшего счёта)
export const fromCentsD = (c) => D(Math.trunc(Number(c) || 0)).dividedBy(100)

// Дирамы → сомони обычным числом — в таком виде суммы отдаёт сервер
export const fromCents = (c) => Math.trunc(Number(c) || 0) / 100

// Сумму с двумя знаками — в сообщения для человека («Долг клиента 12.50 меньше…»).
// Сервер пишет их через toFixed(2) от точного числа; здесь то же самое.
export const fixed2 = (v) => D(v).toFixed(2)
