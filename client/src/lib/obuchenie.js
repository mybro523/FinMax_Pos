// Новый магазин получает программу и не знает, с чего начать. Здесь по каждому
// разделу меню написано: зачем он нужен, что на экране, как сделать обычное дело
// и что бывает не так. Пишем языком продавца, а не разработчика: человек за
// прилавком не знает слов «сущность» и «валидация», зато знает, что покупатель
// просит три штуки из пачки.
//
// Из этих же уроков собираются туры (lib/tury.js). Каждый пункт «Что на экране»
// третьим элементом называет метку настоящего элемента страницы (data-tour):
//   'pos.scan'                       — просто метка;
//   { t, open }                      — элемент внутри формы; open — кнопка, которая её открывает;
//   { t, perm }                      — элемент есть только у тех, кому дано это право;
//   { t, owner }                     — элемент есть только у владельца;
//   { t, missing }                   — что сказать, если элемента сейчас нет на экране;
//   { t, menu }                      — элемент в меню: на телефоне тур откроет меню.
//   { t, pane }                      — касса на узком экране: показать чек ('check') или каталог ('catalog');
//   { t, kogda }                     — шаг только для узкого экрана ('uzko') или только с клавиатурой ('klava').
// Текст пункта обязан описывать ровно то, что на экране: тур подсвечивает живую
// кнопку, и любое расхождение между словами и кнопкой человек увидит сразу.
//
// Правило этого файла: у КАЖДОГО пункта меню есть свой урок. Список уроков
// сверяется со списком меню отдельной проверкой, а метки — с разметкой страниц.

