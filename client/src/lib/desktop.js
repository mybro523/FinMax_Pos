// ── Программа для Windows ──
//
// Один и тот же интерфейс работает и сайтом в браузере, и программой, установленной
// на компьютер магазина. Отличить одно от другого можно по «мосту»: программа кладёт
// в окно объект window.apteka — через него интерфейс разговаривает с основной
// частью программы. В браузере этого объекта нет и быть не может.
//
// Зачем мост, а не обычные запросы из окна:
//   • ключ входа не лежит в окне. В браузере он хранится в localStorage, и любой
//     сценарий на странице может его прочитать. В программе ключ живёт в основной
//     части, зашифрованный средствами Windows, а окно знает только, что вход есть;
//   • окну незачем ходить в интернет самому. Все запросы делает основная часть
//     программы — она же отвечает из локальной базы: касса работает и без интернета.
//
// Модуль намеренно ни от чего не зависит: его подключают и слой данных, и вход,
// и постоянное соединение, а лишние связи здесь превратились бы в кольцо импортов.

export const bridge =
  typeof window !== 'undefined' && window.apteka && window.apteka.desktop === true ? window.apteka : null

export const isDesktop = !!bridge

// Вместо настоящего ключа входа окно программы хранит эту пометку: «вход выполнен».
// Сам ключ в окно не попадает никогда — см. desktop/src/net.mjs
export const DESKTOP_TOKEN = 'desktop'
