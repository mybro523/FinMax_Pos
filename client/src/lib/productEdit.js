// ── Правка карточки товара: что уходит на сервер ──
//
// Форма правки держит все поля карточки, в том числе остаток. Пока она открыта, товар
// продаётся: на сайте, на кассах, чеками, которые касса без интернета досылает позже.
// Если при сохранении отправить остаток из формы, он ляжет поверх настоящего — и
// проданное за эту минуту «вернётся» на полку. Владелец правил цену, а испортил остаток.
//
// Поэтому остаток уходит на сервер, только когда его действительно правили. Тогда это
// осознанное «на полке столько-то» — и сервер считает такую правку пересчётом.

import { isVesovoy, stockUnits } from './units.js'

// Остаток, каким он был в момент открытия формы, — в том же виде, в каком лежит в полях.
// У дробного товара форма держит весь остаток одним числом в килограммах (Products, openEdit):
// «12.35» — и сравнивать надо с ним, а не с целыми упаковками. Иначе остаток с граммами (и
// любой остаток мешками, 1.5.12) считался бы поправленным, хотя его не трогали
export const stockAtOpen = (p) =>
  isVesovoy(p) ? { stock: String(stockUnits(p) / 1000), looseUnits: '0' } : { stock: String(p.stock), looseUnits: String(p.looseUnits ?? 0) }

// data — карточка целиком, как её собрала форма; was — остаток при открытии.
// Возвращает то, что надо отправить
export function editPatch(form, data, was) {
  if (!was) return data
  const touched = String(form.stock) !== was.stock || String(form.looseUnits) !== was.looseUnits
  if (touched) return data
  const { stock: _stock, looseUnits: _loose, ...rest } = data
  return rest
}
