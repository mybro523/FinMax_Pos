// Словарь: русский текст -> таджикский (кириллица). Если перевода нет — показываем русский.
import { useSyncExternalStore } from 'react'

// Язык, как и тема, помнится отдельно для панели владельца сервиса и для магазина:
// в панели он может держать русский, а показывать магазину таджикский — и одно
// другому не мешает. Подробнее о причине — в theme.js.
const KEYS = { apteka: 'apteka_lang', admin: 'apteka_admin_lang' }
export const LANGS = [
  { key: 'ru', label: 'Русский' },
  { key: 'tg', label: 'Тоҷикӣ' },
]

function read(sc) {
  try {
    const v = localStorage.getItem(KEYS[sc])
    return v === 'ru' || v === 'tg' ? v : null
  } catch {
    return null // приватный режим
  }
}

let scope = 'apteka'
let lang = read(scope) || 'ru'

const listeners = new Set()
const emit = () => listeners.forEach((l) => l())

// Переключить сторону. Вызывается один раз при входе, когда уже известна роль
export function setLangScope(sc) {
  const next = sc === 'admin' ? 'admin' : 'apteka'
  if (next === scope) return
  scope = next
  lang = read(scope) || 'ru'
  emit()
}

export function getLang() {
  return lang
}
export function setLang(l) {
  lang = l === 'tg' ? 'tg' : 'ru'
  try {
    localStorage.setItem(KEYS[scope], lang)
  } catch {
    /* ignore */
  }
  emit()
}
export function useLang() {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb)
      return () => listeners.delete(cb)
    },
    () => lang,
    () => 'ru',
  )
}

