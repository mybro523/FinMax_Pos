import { randomBytes, scrypt, scryptSync, timingSafeEqual } from 'node:crypto'

// ── Пароли: правила и хранение, в одном месте ──
// Раньше «минимум четыре символа» было записано в семи файлах, и разъехаться им
// мешало только внимание. Теперь правило одно, и меняется оно здесь.

// ── Длина ──
// Было четыре. Четыре — это 10 000 вариантов у цифрового пароля, а кассир выберет
// именно цифровой. При пяти попытках в четверть часа это чуть больше двух недель
// непрерывного перебора — и никто бы не заметил, оповещений нет.
// Шесть цифр — это уже миллион вариантов и больше четырёх лет. Дальше не идём:
// кассир вводит пароль по десять раз за смену, и слишком длинный он запишет
// на бумажке рядом с кассой, что хуже короткого.
export const MIN_PASSWORD = 6

// Пароли, которые подбираются с первой попытки, длину проходят, но защитой
// не являются. Список короткий и намеренно: это не «проверка стойкости»,
// а отсев того, что человек набирает не думая.
const OBVIOUS = new Set([
  '000000', '111111', '123123', '123321', '123456', '654321', '666666', '696969',
  '121212', '112233', '789456', '999999', 'qwerty', 'qwerty123', 'password', 'parol',
  'parol123', 'abcdef', 'admin1', 'admin123', 'apteka', 'apteka1',
])

// Что не так с паролем. Пусто — всё в порядке.
export function passwordProblem(pw: string): string | null {
  const p = String(pw ?? '')
  if (p.length < MIN_PASSWORD) return `Пароль слишком короткий (минимум ${MIN_PASSWORD} символов)`
  if (OBVIOUS.has(p.toLowerCase())) return 'Такой пароль подберут с первой попытки — придумайте другой'
  if (/^(.)\1+$/.test(p)) return 'Пароль из одного повторяющегося символа не защищает — придумайте другой'
  return null
}

// ── Хранение ──
// scrypt из встроенного crypto, без внешних зависимостей — как и всё остальное
// в этом проекте.
//
// ── Про стоимость и про то, чем я уронил сервер ──
// Сначала стойкость поднималась через N — объём памяти. С N=65536 одна проверка
// пароля требует 64 МБ, и на маленьком контейнере несколько входов подряд съели
// всю память. Сервер упал, Railway перезапустил его трижды и перестал: магазины
// не работали, пока я не выкатил это исправление.
//
// Правильный способ на тесной машине — поднимать не память, а работу: p повторяет
// вычисление, не увеличивая расход. N=16384 с p=4 стоит по времени столько же,
// сколько N=65536, но занимает 16 МБ вместо 64.
//
// Стоимость записана в самом отпечатке, поэтому её можно менять и дальше, не
// выгоняя никого из системы. Отпечатки всех трёх поколений продолжают проверяться.
const N = Number(process.env.PASSWORD_SCRYPT_N || 16384)
const R = 8
const P = Number(process.env.PASSWORD_SCRYPT_P || 4)
const KEYLEN = 64
// Предохранитель: чужой отпечаток не должен заставить сервер запросить гигабайт
const MAXMEM = 96 * 1024 * 1024

// ── Почему не scryptSync ──
// Проверка пароля стоит около четырёхсот миллисекунд процессорного времени на
// машине хостинга — и это НАМЕРЕННО: дорогая проверка делает перебор бессмысленным.
//
// Но синхронный вариант считает эти четыреста миллисекунд прямо в общем потоке,
// то есть весь сервер стоит. Один вход — и все магазины на четыре десятых секунды
// замирают: ни продажи, ни списка товаров, ни даже ответа «я жив». А входят все
// разом, в начале смены: двадцать магазинов в восемь утра — это восемь секунд, когда
// программа не отвечает никому.
//
// Обычный scrypt считает то же самое в отдельном потоке. Стойкость та же, время
// то же, но сервер продолжает работать. Поэтому проверки пароля возвращают
// обещание, а не значение.
const derive = (pw: string, salt: string, n: number, r: number, p: number): Promise<string> =>
  new Promise((ok, fail) => {
    scrypt(pw, salt, KEYLEN, { N: n, r, p, maxmem: MAXMEM }, (e, key) =>
      e ? fail(e) : ok((key as Buffer).toString('hex')),
    )
  })

export async function hashPassword(pw: string): Promise<string> {
  const salt = randomBytes(16).toString('hex')
  return `s3$${N}$${R}$${P}$${salt}$${await derive(pw, salt, N, R, P)}`
}

export async function verifyPassword(pw: string, stored: string): Promise<boolean> {
  try {
    const s = String(stored || '')

    // Нынешний вид: s3$<N>$<r>$<p>$<соль>$<отпечаток>
    if (s.startsWith('s3$')) {
      const [, n, r, p, salt, h] = s.split('$')
      if (!salt || !h) return false
      const [nn, rr, pp] = [Number(n), Number(r), Number(p)]
      if (!(nn >= 1024 && rr >= 1 && pp >= 1 && 128 * nn * rr * pp <= MAXMEM)) return false
      return same(h, await derive(pw, salt, nn, rr, pp))
    }

    // Недолго проживший вид: s2$<N>$<соль>$<отпечаток>, r=8, p=1. Такие отпечатки
    // успели получить те, кто входил между двумя выкладками, — и они обязаны работать.
    if (s.startsWith('s2$')) {
      const [, n, salt, h] = s.split('$')
      const nn = Number(n)
      if (!salt || !h || !(nn >= 1024 && 128 * nn * 8 <= MAXMEM)) return false
      return same(h, await derive(pw, salt, nn, 8, 1))
    }

    // Первоначальный вид: <соль>:<отпечаток>, настройки по умолчанию
    const [salt, h] = s.split(':')
    if (!salt || !h) return false
    // Самый первый вид отпечатков: настройки по умолчанию, считается быстро.
    // Таких почти не осталось — ради них отдельный поток занимать незачем.
    return same(h, scryptSync(pw, salt, KEYLEN).toString('hex'))
  } catch {
    return false
  }
}

// Отпечаток сделан не по нынешним правилам — перепишем при первом же входе
export function isOutdatedHash(stored: string): boolean {
  return !String(stored || '').startsWith(`s3$${N}$${R}$${P}$`)
}

// Сравнение за одинаковое время: обычное сравнение строк выдаёт длину совпадения
// по времени ответа, и по этому можно подбирать отпечаток по одному знаку
function same(a: string, b: string): boolean {
  const x = Buffer.from(a, 'hex')
  const y = Buffer.from(b, 'hex')
  return x.length === y.length && timingSafeEqual(x, y)
}
