// ── Настройки денежных транзакций ──
// Продажа, возврат, приход, списание и пересчёт выполняются одной транзакцией:
// либо всё целиком, либо ничего. Внутри идёт несколько запросов подряд, и стандартных
// 5 секунд Prisma не хватало — при малейшей задержке сети транзакция закрывалась
// на полпути, а кассир видел невнятную «ошибку запроса к базе данных» (код P2028).
//
// maxWait — сколько ждать свободное подключение к базе,
// timeout — сколько отводится на саму операцию.

export const TX = { maxWait: 20000, timeout: 60000 }

// Инвентаризация может затрагивать сотни товаров сразу — ей нужен запас побольше
export const TX_LONG = { maxWait: 20000, timeout: 180000 }

// ── Чтение одним снимком ──
// Касса без интернета спрашивает «что изменилось с прошлого раза». Отметка «до какой
// транзакции смотрим» и сами данные обязаны браться из одного состояния базы: иначе
// между двумя запросами вклинится продажа, и её изменения касса не увидит никогда.
// Время — как у денежных операций: первая загрузка отдаёт весь магазин целиком.
export const TX_SNAPSHOT = { ...TX, isolationLevel: 'RepeatableRead' as const }

