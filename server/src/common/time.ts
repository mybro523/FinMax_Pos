// ── Время магазина на сервере: Таджикистан (Asia/Dushanbe, UTC+5, без переходов) ──
// Сервер стоит в чужом часовом поясе и живёт по UTC. Если считать «сегодня» по нему,
// то с полуночи до пяти утра по Душанбе сервер думает, что ещё вчера, — и товар,
// у которого срок закончился, ещё несколько часов считался бы годным.
//
// Клиент считает так же (client/src/lib/time.js), иначе экран «Срок годности»
// и касса расходились бы в пограничные дни.

const TJ_OFFSET_MS = 5 * 60 * 60 * 1000 // +05:00

// ── Дата, которую можно сохранить ──
// База принимает даты с годом от 1 до 9999. А поле даты в браузере пускает и шесть
// цифр года: «20266» вместо «2026» — обычная опечатка. Такая дата — настоящая дата
// для программы, и раньше запрос падал уже в базе: на сайте человек видел «внутренняя
// ошибка сервера» вместо подсказки, а операцию кассы сервер не мог записать никогда —
// и за ней вставала вся её очередь.
const MIN_DATE_MS = Date.parse('0001-01-01T00:00:00.000Z')
const MAX_DATE_MS = Date.parse('9999-12-31T23:59:59.999Z')
export const storableDate = (t: number): boolean => t >= MIN_DATE_MS && t <= MAX_DATE_MS

// Начало сегодняшних суток по Душанбе, как абсолютный момент времени
export function startOfTodayTj(now: Date = new Date()): Date {
  const shifted = new Date(now.getTime() + TJ_OFFSET_MS)
  return new Date(shifted.toISOString().slice(0, 10) + 'T00:00:00.000+05:00')
}

// Календарная дата по Душанбе в виде «2026-08-22». Нужна там, где важен именно
// день, а не момент: «эту работу за сегодня уже делали».
export function dayKeyTj(now: Date = new Date()): string {
  return new Date(now.getTime() + TJ_OFFSET_MS).toISOString().slice(0, 10)
}

// Просрочена ли партия. Срок годности — ПОСЛЕДНИЙ день, когда товар годен:
// «годен до 20.08» означает, что 20-го продавать ещё можно, а 21-го уже нет.
// Пустой срок (бинты, вата, приборы) просроченным не считается никогда.
export function isExpired(date: Date | null | undefined, now?: Date): boolean {
  if (!date) return false
  return date.getTime() < startOfTodayTj(now).getTime()
}
