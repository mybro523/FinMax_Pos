// ── С какого места отдавать кассе изменения ──
//
// Касса называет отметку прошлого обмена, а сервер решает: досылать изменения с неё
// или отдать весь магазин заново. Отметка — номер транзакции базы; они только растут.
//
// Модуль не знает ни про базу, ни про Nest — только решение. Проверяется отдельно.

// Отметка из запроса: число в виде строки (в JSON оно не помещается)
export const mark = (v?: string | null): bigint | null => (/^\d{1,19}$/.test(v || '') ? BigInt(v as string) : null)

export interface CursorFacts {
  // Отметка, которую назвала касса. Пусто — она просит всё с нуля
  asked: bigint | null
  // Её же отметка разделов владельца — списаний и расходов (только у владельца)
  askedW: bigint | null
  // До какой транзакции журнал изменений уже подчищен
  pruned: bigint
  // Все транзакции с номером меньше этого завершены и видны
  horizon: bigint
  // Отметка, которую сервер выдал этой кассе в прошлый раз. Пусто — не выдавал
  given: bigint | null
}

// Номер транзакции, с которой досылать изменения, или null — отдать всё заново
export function sinceOf({ asked, askedW, pruned, horizon, given }: CursorFacts): bigint | null {
  // Первый обмен
  if (asked === null) return null
  // Журнал за это время подчищен — досылать нечем
  if (asked < pruned) return null
  // Отметка «из будущего»: такой транзакции в этой базе ещё не было
  if (asked > horizon) return null
  // Касса называет отметку, которой этот сервер ей не выдавал: он о ней не помнит
  // вовсе или помнит более раннюю. Так бывает, когда базу сервера подняли из копии
  // или перенесли: касса успела получить то, чего в базе теперь нет. Досылать ей
  // «изменения» бессмысленно — у неё останутся товары и чеки, которых на сервере
  // уже не существует. (Обратное — отметка кассы старше выданной — обычное дело:
  // прошлый ответ не дошёл, или кассу саму подняли из её копии.)
  if (given === null || asked > given) return null
  // Отметка разделов владельца старше подчищенного журнала — добрать их нечем
  if (askedW !== null && askedW < pruned) return null
  return asked
}
