import { Injectable } from '@nestjs/common'
import { randomBytes } from 'node:crypto'

// ── Отметка «когда этот раздел менялся в последний раз» ──
//
// Нужна затем, чтобы не отдавать одно и то же дважды. Список товаров у настоящей
// магазина — несколько тысяч наименований, и он почти не меняется: приход бывает
// раз в день, а забирать его заново приходилось при каждом обновлении экрана.
//
// Теперь браузер спрашивает: «у меня версия такая-то, что-нибудь изменилось?» —
// и если нет, получает пустой ответ «то же самое». Ни мегабайтов по сети, ни
// разбора их в браузере, ни даже похода в базу: ответ известен до начала работы.
//
// ── Откуда берётся счётчик ──
// Из того же места, что и оповещения устройствам: каждое изменение уже проходит
// через одну точку (EventsGateway.changedIn). Второго списка «что от чего зависит»
// заводить не пришлось — а значит, и разъехаться им негде.
//
// ── Почему в отметке есть имя запуска ──
// Счётчик живёт в памяти. После перезапуска он начинается заново, и старая отметка
// у браузера случайно совпала бы с новой — он получил бы «то же самое», хотя за это
// время могло измениться всё. Имя запуска у каждого сервера своё, поэтому такая
// отметка просто не совпадёт: браузер получит свежий ответ.
//
// По той же причине это верно работает и когда серверов станет несколько: отметка
// от одного не подойдёт другому, и тот честно отдаст всё заново.
@Injectable()
export class ChangeStamp {
  // Своё при каждом запуске каждого сервера
  readonly run = randomBytes(5).toString('hex')
  private readonly v = new Map<string, number>()

  private key(schema: string, collection: string) {
    return `${schema}|${collection}`
  }

  bump(schema: string, collections: string[]) {
    if (!schema) return
    for (const c of collections) {
      const k = this.key(schema, c)
      this.v.set(k, (this.v.get(k) || 0) + 1)
    }
  }

  of(schema: string, collection: string): number {
    return this.v.get(this.key(schema, collection)) || 0
  }

  // Полная отметка для ответа. В неё входит и сам адрес запроса: у одного раздела
  // бывают разные выборки, и путать их ответы нельзя.
  tag(schema: string, collection: string, url: string): string {
    return `W/"${this.run}.${this.of(schema, collection)}.${hash(schema + url)}"`
  }
}

// Короткий отпечаток строки. Не для защиты, а чтобы отметка не разрасталась:
// сравнивать её будут при каждом запросе.
function hash(s: string): string {
  let h = 0x811c9dc5
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return (h >>> 0).toString(36)
}
