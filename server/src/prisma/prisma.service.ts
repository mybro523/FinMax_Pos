import { Injectable } from '@nestjs/common'
import { PrismaClient } from '@prisma/client'
import { TenantPool } from './tenant-pool.service'

// ── Доступ к данным того магазина, который обслуживает текущий запрос ──
// У каждого магазина своя схема Postgres. Выбирать её должен кто-то один, иначе
// пришлось бы дописать аргумент в каждое из полутора сотен обращений к базе —
// и в шесть мест, где написан сырой SQL, а их не прикрыл бы никакой автоматический
// фильтр. Одно забытое место означало бы, что один магазин видит данные другого.
//
// Поэтому подстановка живёт здесь. Снаружи ничего не изменилось: сервисы
// по-прежнему пишут this.prisma.product.findMany(…) и ничего не знают про схемы.
// Обращение перехватывается и уходит в клиент нужного магазина — его подбирает
// TenantPool по контексту запроса.
//
// Класс наследует PrismaClient только ради типов: сервисы должны видеть привычный
// набор моделей. Сам базовый экземпляр не используется — Prisma подключается
// к базе при первом запросе, а запросов к нему не будет ни одного.
@Injectable()
export class PrismaService extends PrismaClient {
  constructor(pool: TenantPool) {
    super()
    // Возврат из конструктора подменяет создаваемый объект. Ссылку на пул держим
    // в замыкании, а не полем: любое собственное поле пришлось бы исключать из
    // подстановки, а забытое исключение увело бы запрос не в ту схему.
    return new Proxy(this, {
      get: (_target, prop) => {
        const client = pool.current() as any
        const value = client[prop]
        // Методы привязываем к их клиенту: иначе внутри Prisma this указывал бы
        // на подставной объект, а не на настоящее подключение
        return typeof value === 'function' ? value.bind(client) : value
      },
    })
  }
}
