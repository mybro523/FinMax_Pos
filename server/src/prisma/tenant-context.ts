import { AsyncLocalStorage } from 'node:async_hooks'

// ── Какой магазин обслуживается прямо сейчас ──
// У каждого магазина своя схема Postgres. Значит, на каждый запрос надо знать, в чью
// схему идти. Протаскивать это через все сервисы означало бы дописать аргумент
// в каждую из полутора сотен функций — и в шесть мест, где написан сырой SQL.
//
// Поэтому имя схемы кладётся в хранилище, привязанное к самому запросу. Оно
// проходит сквозь await и вложенные вызовы, но не протекает в соседний запрос:
// у каждого своё. Сервисы про него не знают вовсе — за них схему подставляет
// PrismaService.
//
// Вне запроса контекста нет: почасовой пересчёт просрочки, миграции, заведение
// магазина обходят схемы сами и объявляют нужную явно через runInTenant.

const store = new AsyncLocalStorage<string>()

// Схема магазина для текущего запроса. Пусто — контекст не задан.
export function currentTenantSchema(): string | undefined {
  return store.getStore()
}

// Выполнить работу в контексте конкретного магазина. Всё, что случится внутри —
// включая продолжения после await, — будет ходить в её схему.
export function runInTenant<T>(schema: string, fn: () => T): T {
  return store.run(schema, fn)
}
