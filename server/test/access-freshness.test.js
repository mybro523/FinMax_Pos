// ── Страховка от забытого сброса памяти сторожа ──
//
// Сторож помнит сотрудника несколько секунд, чтобы не ходить в базу на каждый
// запрос. Расплата за это — обязанность сбрасывать память везде, где доступ
// действительно меняется.
//
// Забыть такое место легко и совершенно незаметно: ошибок нет, ответы правильные,
// просто заблокированный кассир работает ещё несколько секунд, а оплаченная аптека
// столько же получает отказы. Заметить это в работе почти невозможно — «показалось».
//
// Поэтому читаем исходники и требуем сброс в каждом действии, которое меняет доступ.
//
// Запуск: npm test (в папке server).
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const SRC = path.join(__dirname, '..', 'src')

// На Windows строки в файлах заканчиваются возвратом каретки, и поиск по концу
// метода не находил бы ничего — проверка молча проходила бы мимо всего
function read(rel) {
  return fs
    .readFileSync(path.join(SRC, rel), 'utf8')
    .split(String.fromCharCode(13))
    .join('')
}

// Тело метода: от объявления до закрывающей скобки с тем же отступом
function methodBody(rel, name) {
  const src = read(rel)
  const at = src.search(new RegExp('^  (?:async )?' + name + '[(]', 'm'))
  assert.notEqual(at, -1, `метод ${name}() пропал из ${rel} — проверка устарела`)
  const end = src.indexOf('\n  }\n', at)
  assert.notEqual(end, -1, `не нашёл конец метода ${name}() в ${rel}`)
  return src.slice(at, end)
}

test('правка сотрудника сбрасывает память сторожа', () => {
  // Здесь меняются пароль, роль и сам факт доступа. Всё это обязано
  // подействовать сейчас, а не через несколько секунд.
  const body = methodBody('users/users.service.ts', 'update')
  assert.match(body, /this\.accounts\.drop\(/, 'заблокированный сотрудник продолжит работать')
})

test('удаление сотрудника сбрасывает память сторожа', () => {
  const body = methodBody('users/users.service.ts', 'remove')
  assert.match(body, /this\.accounts\.drop\(/, 'удалённый сотрудник продолжит работать')
})

test('смена своего пароля сбрасывает память сторожа', () => {
  // Смена пароля отзывает все прежние токены. Если сторож этого не заметит,
  // утёкший токен поработает ещё немного — а смена пароля была единственным,
  // что могло его остановить.
  const body = methodBody('auth/auth.service.ts', 'changePassword')
  assert.match(body, /this\.accounts\.drop\(/, 'старый токен ещё поработает')
})

test('всё, что меняет подписку аптеки, сбрасывает память сторожа', () => {
  // Иначе клиент, который только что заплатил, ещё несколько секунд получал бы
  // отказ в продаже — и позвонил бы второй раз, теперь уже рассерженным
  for (const m of ['extend', 'setBlocked', 'update', 'remove']) {
    const body = methodBody('admin/pharmacies.service.ts', m)
    assert.match(body, /this\.accounts\.dropPharmacy\(/, `${m}(): аптека узнает о своём новом состоянии не сразу`)
  }
})

test('сторож не ходит в базу сам — только через память', () => {
  // Прямой запрос в обход памяти вернул бы те самые сто тридцать пять миллисекунд
  // на каждый запрос, и никто бы этого не заметил
  const guard = read('auth/auth.guard.ts')
  assert.doesNotMatch(guard, /this\.admin\.account\./, 'сторож снова ходит в базу напрямую')
  assert.match(guard, /this\.accounts\.get\(/, 'сторож перестал пользоваться памятью')
})

test('«кто я» не ходит в базу второй раз', () => {
  // Программа спрашивает это при запуске, при каждом возвращении на вкладку и после
  // каждого изменения подписки. Сторож на входе только что спросил то же самое.
  const body = methodBody('auth/auth.service.ts', 'me')
  assert.match(body, /this\.accounts\.get\(/, 'лишний поход в базу на самом частом запросе')
  assert.doesNotMatch(body, /this\.admin\.account\./, 'снова спрашиваем базу напрямую')
})

test('память сторожа живёт секунды, а не минуты', () => {
  // Срок — страховка на случай забытого места сброса. Сделать его большим значит
  // сделать эту страховку бесполезной.
  const cache = read('admin/account-cache.service.ts')
  const m = cache.match(/ACCOUNT_CACHE_MS \|\| ([0-9_]+)/)
  assert.ok(m, 'не нашёл срок жизни')
  const ms = Number(m[1].replace(/_/g, ''))
  assert.ok(ms <= 30_000, `срок жизни ${ms} мс — слишком долго для отобранного доступа`)
  assert.ok(ms >= 1_000, `срок жизни ${ms} мс — памяти нет смысла`)
})
