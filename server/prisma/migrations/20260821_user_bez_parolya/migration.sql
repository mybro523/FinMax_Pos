-- Пароль сотрудника переехал в панель управления (схема admin, таблица Account).
-- Вход теперь общий на весь сервис: логин уникален у всех аптек сразу, и по нему
-- система понимает, в какую аптеку пускать. Здесь остаются только имя и роль —
-- на них ссылаются чеки, смены, возвраты и списания.
--
-- Копию пароля тут держать нельзя: это вторая правда о доступе. Однажды кто-то
-- стал бы проверять её вместо настоящей, и заблокированный сотрудник продолжил бы
-- входить, пока это не заметили бы по выручке.
ALTER TABLE "User" DROP COLUMN IF EXISTS "passwordHash";
ALTER TABLE "User" DROP COLUMN IF EXISTS "passwordChangedAt";
