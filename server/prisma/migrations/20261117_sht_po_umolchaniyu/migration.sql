-- ── Единица «шт» по умолчанию (17.11.2026) ──
--
-- Владелец: товары по умолчанию — в штуках, а не в упаковках. Новый товар без единицы
-- получает «шт». Уже заведённые «уп», у которых в упаковке одна штука (unitsPerPack = 1),
-- — тоже «шт»: «1 уп» из одной штуки — это штука. Остатки, цены и история не меняются —
-- только подпись. Настоящие упаковки (внутри больше одной штуки) остаются «уп», товары на
-- вес (кг, л, м) — в своей единице. Пустая единица считается так же (её показывали «уп»).
--
-- ВАЖНО: прежним программам миграция не мешает — единица у товара была и раньше.

ALTER TABLE "Product" ALTER COLUMN "unit" SET DEFAULT 'шт';

UPDATE "Product" SET "unit" = 'шт' WHERE ("unit" = 'уп' OR btrim("unit") = '') AND "unitsPerPack" <= 1;
