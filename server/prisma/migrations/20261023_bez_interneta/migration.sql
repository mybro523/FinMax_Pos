-- ── Всё — и без интернета ──
--
-- Программа для Windows теперь заводит и правит без связи и справочники: товары,
-- поставщиков, категории, типы, статьи, сервисы перевода, — а правки присылает потом.
-- Пока она была без связи, то же поле могли поправить на сайте. Побеждает последняя
-- правка по времени, и для этого сервер помнит, когда каждое поле правили в последний
-- раз. Если правки столкнулись — владелец видит это в «Расхождениях»: подробности
-- (какое поле, что было у кассы и что на сервере) лежат в новом столбце note.
--
-- ВАЖНО: нынешней программе миграция не мешает. Новую таблицу и столбец она не читает.

CREATE TABLE IF NOT EXISTS "FieldStamp" (
    "tbl" TEXT NOT NULL,
    "rowId" TEXT NOT NULL,
    "field" TEXT NOT NULL,
    "at" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "FieldStamp_pkey" PRIMARY KEY ("tbl", "rowId", "field")
);

ALTER TABLE "Discrepancy" ADD COLUMN IF NOT EXISTS "note" TEXT NOT NULL DEFAULT '';
